/**
 * Generate TypeScript type definitions for the pipeline
 * 
 * @param compiledFunctions - Array of compiled functions
 * @returns TypeScript definitions
 */
export function generateTypeDefinitions(compiledFunctions: CompiledFunction[]): string {
  const modelIds = compiledFunctions.map(f => `"${f.id}"`).join(' | ');
  
  return `// TypeScript definitions for the generated pipeline
export interface GeneratedPipeline {
  getAvailableModels(): Array<{
    id: ${modelIds};
    name: string;
    type: 'static' | 'parametric';
  }>;
  
  generateModel(modelId: ${modelIds}, params?: any): Promise<any>;
  getModelConfig(modelId: ${modelIds}): any;
  getPipelineInfo(): {
    version: string;
    modelCount: number;
    generatedAt: string;
    models: any[];
  };
}`;
}

/**
 * Validate that all compiled functions are valid
 * 
 * @param compiledFunctions - Array of compiled functions to validate
 * @returns Validation result with any errors
 */
export function validateCompiledFunctions(compiledFunctions: CompiledFunction[]): {
  isValid: boolean;
  errors: string[];
} {
  const errors: string[] = [];

  // Check for duplicate IDs
  const ids = compiledFunctions.map(f => f.id);
  const duplicateIds = ids.filter((id, index) => ids.indexOf(id) !== index);
  if (duplicateIds.length > 0) {
    errors.push(`Duplicate model IDs found: ${duplicateIds.join(', ')}`);
  }

  // Check for empty function names
  const emptyNames = compiledFunctions.filter(f => !f.functionName);
  if (emptyNames.length > 0) {
    errors.push(`Functions with empty names: ${emptyNames.map(f => f.id).join(', ')}`);
  }

  // Check for empty function code
  const emptyCode = compiledFunctions.filter(f => !f.functionCode);
  if (emptyCode.length > 0) {
    errors.push(`Functions with empty code: ${emptyCode.map(f => f.id).join(', ')}`);
  }

  return {
    isValid: errors.length === 0,
    errors
  };
}
